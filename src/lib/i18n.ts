export type MessageKey = keyof typeof messages.en

export function t(key: MessageKey, activeLocale: AppLocale = 'en'): string {
  return messages[activeLocale][key] ?? messages.en[key] ?? key
}

export function tCategory(slug: string, activeLocale: AppLocale = 'en'): string {
  const key = `category.${slug}` as MessageKey
  if (key in messages.en) return t(key, activeLocale)
  return slug
}

export function tPropertyType(type: string, activeLocale: AppLocale = 'en'): string {
  const key = `type.${type}` as MessageKey
  if (key in messages.en) return t(key, activeLocale)
  return type.charAt(0).toUpperCase() + type.slice(1)
}
